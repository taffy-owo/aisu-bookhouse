import { buildApiResourceUrl } from '../../../shared/api';
import type { Book } from '../types/book';
import type { BackendBook } from './bookApiTypes';

export function mapBackendBook(book: BackendBook): Book {
  return {
    author: book.author,
    coverUrl: buildApiResourceUrl(book.cover_url),
    createdAt: book.created_at,
    currentChapter: book.current_chapter ?? undefined,
    description: book.description,
    favorite: book.favorite,
    disliked: book.disliked,
    fileExt: book.file_ext ?? undefined,
    fileSize: book.file_size ?? undefined,
    heroImageUrl: book.hero_image_url ?? undefined,
    id: book.id,
    isOwned: book.is_owned,
    kind: book.kind,
    language: book.language,
    languageMode: book.language_mode ?? (book.language === 'und' ? 'auto' : 'manual'),
    mimeType: book.mime_type ?? undefined,
    progressPercent: book.progress_percent,
    publicationStatus: book.publication_status,
    autoTranslateUpdates: book.auto_translate_updates ?? false,
    publicApprovedAt: book.public_approved_at ?? undefined,
    publicDownloadAllowed: book.public_download_allowed,
    publicRejectedAt: book.public_rejected_at ?? undefined,
    publicRequestedAt: book.public_requested_at ?? undefined,
    publicShareNote: book.public_share_note ?? undefined,
    publicSourceNote: book.public_source_note ?? undefined,
    publicStatus: book.public_status,
    rating: book.rating,
    readersLabel: book.readers_label,
    readerType: book.reader_type,
    seriesKind: book.series_kind ?? undefined,
    seriesOrder: book.series_order ?? undefined,
    seriesTitle: book.series_title ?? undefined,
    sourceUrl: book.source_url ?? undefined,
    sourceEpisodeCount: book.source_episode_count ?? undefined,
    sourceCharacterCount: book.source_character_count ?? undefined,
    sourceUpdateCount: book.source_update_count ?? 0,
    sourceCheckedAt: book.source_checked_at ?? undefined,
    sourceCheckError: book.source_check_error ?? undefined,
    sourceScheduleTime: book.source_schedule_time ?? undefined,
    sourceScheduleTimezone: book.source_schedule_timezone ?? undefined,
    sourceScheduleLabel: book.source_schedule_label ?? undefined,
    status: book.status,
    subtitle: book.subtitle ?? undefined,
    tags: book.tags,
    title: book.title,
    updatedAt: book.updated_at,
    lastReadAt: book.last_read_at ?? undefined,
    version: book.version ?? undefined,
    ownerId: book.owner_id,
    ownerNickname: book.owner_nickname ?? undefined,
    commentCount: book.comment_count,
    chapterCount: book.chapter_count,
    pageCount: book.page_count,
    characterCount: book.character_count,
    assetCount: book.asset_count,
    lastContentUpdatedAt: book.last_content_updated_at ?? undefined,
  };
}
